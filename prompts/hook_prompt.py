def build_hook_prompt(language: str | None = None) -> str:
    guidance = LANGUAGE_GUIDANCE.get((language or "").lower(), "")
    return HOOK_SYSTEM_PROMPT + guidance


# Where this precap sits in its anchor run — position and pacing ONLY.
#
# It deliberately does not say what to name or withhold: HOW MUCH TO REVEAL
# already does that, and the planner wrote it having read the actual scene,
# whereas anything here is derived from the distance alone and is blind to the
# content. When the two were both prescribing content they could contradict each
# other outright — a distance-4 precap whose reveal legitimately names the object
# was being told in the same prompt to leave the object alone.
#
# What this genuinely knows and the reveal does not: how many precaps still
# follow this one. Under the sticky-anchor rule a run counts down to its target,
# so distance - 1 is exactly the number that come after it.


def _run_position_note(mapping) -> str:
    followers = mapping.distance - 1

    if followers == 0:
        return (
            "This is the LAST precap reaching for this scene — the reader arrives in the very "
            "next chapter. Nothing comes after you to finish what you start, so there is no reason "
            "to hold anything back beyond what HOW MUCH TO REVEAL withholds. Land it."
        )

    following = "1 more precap" if followers == 1 else f"{followers} more precaps"
    note = (
        f"{following} after this one will reach for this SAME scene before the reader gets there, "
        "and each will be allowed to name more than you are. Pace accordingly: your job is to move "
        "the listener one step closer, not to arrive."
    )
    if followers >= 3:
        note += (
            " You are at the top of the run, so this is the quietest look at the scene there will "
            "be — aim for curiosity rather than alarm."
        )
    return note + (
        " HOW MUCH TO REVEAL above is the authority on what you may name; if anything here seems "
        "to pull against it, follow the reveal."
    )
def build_bridge_context(
    mapping,
    previous_reveal: str | None = None,
    same_scene_precaps: list[str] | None = None,
    previous_precap: str | None = None,
) -> str:
    """The Pass 1 blueprint row for this chapter (see
    pipeline/arc_planning.py::ChapterMapping) rendered as extra user-message
    context, plus what the preceding precap in the same anchor run did.

    Each block labels what its datum IS and what is specific to it. The rules
    themselves — withhold the outcome, say nothing about the unread chapters in
    between, never let an internal note's English wording reach the hook, never
    echo the previous precap — all live in the system prompt, and are not
    restated here. Stating a rule twice in one prompt is how the two copies
    drift apart, which is exactly what happened when the run-position note also
    tried to say what may be named.

    Precedence, where two blocks could pull against each other: HOW MUCH TO
    REVEAL governs what may be named, and everything else yields to it.

    The three predecessor inputs have different scopes and different jobs:

    * `previous_reveal` is run-scoped — how far the disclosure of THIS scene had
      got one chapter ago. Meaningless across a run boundary, so the caller
      passes it only within a run.
    * `same_scene_precaps` is every precap already written for this same scene,
      the whole run so far. These are the ones at real risk of saying the same
      thing twice, because they are about the same moment.
    * `previous_precap` is simply the one before this chapter. Mid-run it is
      already among the same-scene precaps and is dropped here rather than sent
      twice, so this block only appears at a run boundary — where the listener
      has just heard a precap about a different scene and the risk is a repeated
      shape rather than repeated content."""
    parts = []

    if mapping is not None:
        distance = mapping.distance
        gap = (
            "It is in the very next chapter, so the reader reaches it immediately."
            if distance == 1
            else (
                f"It is {distance} chapters ahead, and the reader has not read the "
                + ("1 chapter" if distance == 2 else f"{distance - 1} chapters")
                + " in between."
            )
        )
        parts.append(
            "\n\nTARGET SCENE (internal — the scene this hook reaches for):\n"
            f"{mapping.scene_description}\n{gap}"
        )

        if mapping.dominant_emotion:
            parts.append(
                "\n\nDOMINANT EMOTION (internal — the one feeling this precap must leave the "
                "listener holding. It was assigned across the whole series so that neighbouring "
                "precaps land different feelings, so it is not yours to swap for an easier "
                f"one):\n{mapping.dominant_emotion}"
            )

        if mapping.reveal:
            parts.append(
                "\n\nHOW MUCH TO REVEAL (internal — your step in a run of precaps all reaching "
                "for the scene above, and the authority on what this one may name. The limits "
                "bind as tightly as the permissions, and so does the floor: naming less than this "
                f"allows leaves the run with nothing to pay off):\n{mapping.reveal}"
            )

        parts.append(
            f"\n\nWHERE THIS PRECAP SITS (internal):\n{_run_position_note(mapping)}"
        )

        if mapping.bridge_reasoning:
            parts.append(
                "\n\nWHY THIS SCENE (internal — the thread from the chapter just read to the "
                f"target scene; it is the hook's angle):\n{mapping.bridge_reasoning}"
            )

    if previous_reveal:
        # Deliberately no "don't reuse its wording" here: a reveal is a planning
        # instruction the reader never saw, so there is no wording to avoid.
        # That rule belongs only on the precap text below.
        parts.append(
            "\n\nWHAT THE PREVIOUS PRECAP WAS ALLOWED TO NAME (internal — it reached for this "
            f"same scene and got this far. Yours goes further):\n{previous_reveal}"
        )

    if same_scene_precaps:
        listed = "\n\n".join(
            f"({n} of {len(same_scene_precaps)}):\n{text}"
            for n, text in enumerate(same_scene_precaps, start=1)
        )
        parts.append(
            "\n\nEVERY PRECAP ALREADY WRITTEN FOR THIS SAME SCENE, IN ORDER (internal — the "
            "listener has heard all of these, each reaching for the very scene yours reaches for. "
            "Between them they have already spent a set of words, images and angles on it. Yours "
            "must go past ALL of them, not just the last: say something none of them said, and do "
            "not reach again for an image or a phrase any of them already used. If your draft "
            f"would sit unnoticed among these, it is not a new precap):\n{listed}"
        )

    # Mid-run the previous precap is already listed above; sending it again under
    # a second heading would just weight it twice.
    if previous_precap and previous_precap not in (same_scene_precaps or []):
        parts.append(
            "\n\nTHE PRECAP IMMEDIATELY BEFORE THIS ONE, WORD FOR WORD (internal — the listener "
            "heard this one chapter ago, about a different scene. The risk here is not repeated "
            "content but repeated shape: do not reuse its opening move, its pivot phrase, its "
            "images, or the construction of its closing question. Heard back to back, a repeated "
            f"shape reads as one precap played again however different the events are):\n"
            f"{previous_precap}"
        )

    return "".join(parts)
